/**
 * Подсказка о прокрутке узкой строки меню.
 *
 * В шапке на телефоне разделы не помещаются в одну строку: строка
 * прокручивается вбок, а полосы прокрутки у неё нет. Чтобы читатель понял,
 * что справа (или слева) есть ещё пункты, край строки приглушается.
 * Когда прокручивать нечего, приглушать нечего — иначе последний пункт
 * выглядел бы выцветшим.
 *
 * Функция чистая: считает по размерам строки, без обращения к DOM.
 */

/** Размеры прокручиваемой строки. */
export type ScrollFadeSizes = {
  /** Ширина всего содержимого строки вместе с прокрученной частью. */
  scrollWidth: number;
  /** Видимая ширина строки. */
  clientWidth: number;
  /** Текущее смещение прокрутки от начала строки. */
  scrollLeft: number;
};

/** С каких краёв строки нужно приглушить содержимое. */
export type ScrollFadeEdges = {
  /** Слева есть прокрученное содержимое. */
  left: boolean;
  /** Справа есть ещё содержимое. */
  right: boolean;
};

/**
 * Какие края строки приглушить.
 *
 * Край приглушается, только если строка прокручивается и этот край ещё
 * не показан целиком. Запас в один пиксель: из-за дробных значений
 * вёрстки разница бывает в пол-пикселя, и без запаса край мерцает.
 */
export function scrollFadeEdges({
  scrollWidth,
  clientWidth,
  scrollLeft,
}: ScrollFadeSizes): ScrollFadeEdges {
  const scrollable = scrollWidth - clientWidth;

  // Прокручивать нечего — приглушать нечего.
  if (scrollable <= 1) {
    return { left: false, right: false };
  }

  return {
    left: scrollLeft > 1,
    right: scrollLeft < scrollable - 1,
  };
}
