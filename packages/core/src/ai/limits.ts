/**
 * Ограничения помощника — в одном месте.
 *
 * Числа живут здесь, а не в текстах страниц, по двум причинам: правила
 * показываются и на сайте, и в телеграм-боте, и в двух местах они должны
 * совпадать. Плюс это единственный способ не разойтись с кодом: лимиты
 * меняются в одном файле, а страница правил подтягивает их оттуда.
 */

import { WEB_WORK_MODES, type WorkMode } from "./workModes";

/** Режим работы помощника: каталог, поиск, рассуждение или ресёрч. */
export type LimitWorkMode = WorkMode;

/** Режим ответа: коротко, по шагам или почему. */
export type LimitAnswerMode = "short" | "steps" | "why";

/** Ограничения помощника. */
export const ASSISTANT_LIMITS = {
  /**
   * Каталог: запросов в минуту с одного адреса.
   *
   * Обычный ответ по каталогу стоит недорого, поэтому лимит щедрый.
   */
  catalogPerMinute: 20,

  /**
   * Режимы с интернетом: запросов в минуту с одного адреса.
   *
   * Эти режимы ходят в интернет и стоят заметно дороже, поэтому запросов
   * разрешено меньше.
   */
  webPerMinute: 8,

  /** Длина вопроса в символах. */
  maxQuestionLength: 1000,

  /** Сообщений, которые можно передать в одном запросе. */
  maxHistoryMessages: 10,

  /** Реплик диалога, которые уходят в конвейер вместе с вопросом. */
  historyMessages: 6,

  /** Вопросов в блоке «Что спросить дальше». */
  maxFollowUps: 3,

  /** Бюджет токенов ответа в режиме «Коротко». */
  shortTokens: 900,

  /** Бюджет токенов ответа в режиме «Почему». */
  whyTokens: 3600,

  /**
   * Бесплатные модели провайдера: запросов в минуту.
   *
   * Ограничение задаёт провайдер, а не сайт. Если бесплатные модели
   * недоступны, помощник переключается на платные — это видно по времени
   * ответа и по подписи модели.
   */
  freeModelsPerMinute: 5,
} as const;

/** Человеческое название режима ответа. */
export const LIMIT_ANSWER_LABELS: Record<LimitAnswerMode, string> = {
  short: "Коротко",
  steps: "По шагам",
  why: "Почему",
};

/** Режим, который отвечает только по каталогу. */
export const CATALOG_WORK_MODE: LimitWorkMode = "chat";

/**
 * Лимит запросов в минуту для режима работы.
 *
 * Режимы с интернетом ограничены жёстче: они дороже и медленнее.
 */
export function perMinuteLimit(mode: LimitWorkMode): number {
  return (WEB_WORK_MODES as readonly string[]).includes(mode)
    ? ASSISTANT_LIMITS.webPerMinute
    : ASSISTANT_LIMITS.catalogPerMinute;
}

