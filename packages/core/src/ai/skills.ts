/** Навыки, работающие с интернетом. */
export type SkillName = "search" | "reason" | "research";

/** Описание навыка. */
export type Skill = {
  name: SkillName;
  /** Подпись в интерфейсе. */
  label: string;
  /** Какая цепочка моделей используется. */
  modelKind: "fast" | "reason";
  /** Сколько запросов в интернет делать. */
  maxQueries: number;
  /** Сколько источников показывать в ответе. */
  maxSources: number;
  /** Сколько символов текста источника уходит в промт. */
  snippetLimit: number;
  /** Бюджет токенов на ответ. */
  maxTokens: number;
  /** Инструкция режима для модели. */
  instruction: string;
  /**
   * Инструкция для короткого ответа.
   *
   * Отдельная, потому что развёрнутая просит разделы и списки, а короткий
   * ответ это не укладывает: модель получает противоречащие друг другу
   * указания и обрезает ответ.
   */
  shortInstruction: string;
};

