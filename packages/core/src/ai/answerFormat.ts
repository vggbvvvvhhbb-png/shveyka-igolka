/**
 * Приводит ответ модели к виду, который приятно читать.
 *
 * Модели часто оставляют в тексте мелкие огрехи: пробел перед точкой, пустые
 * строки через две, висячие пробелы в конце строки. Такие огрехи бросаются в
 * глаза и портят впечатление от ответа, хотя по смыслу всё верно.
 *
 * Здесь же разбирается блок «Что спросить дальше» — модель пишет его в конце
 * ответа, а интерфейс показывает вопросы кнопками.
 */

/**
 * Правила оформления ответа: интерфейс разбирает разметку.
 *
 * Правила общие для всех режимов — и для каталожного, и для режимов
 * с интернетом: ответ должен читаться одинаково, какой бы путь к нему ни
 * привёл.
 */
export const FORMAT_RULES = [
  "Оформляй ответ разметкой — интерфейс её разбирает:",
  "- короткие абзацы и списки вместо сплошного текста;",
  "- заголовки разделов: ## Заголовок;",
  "- выделение главного: **важное**;",
  "- не начинай с вступлений вроде «Конечно!» и «Давайте разберёмся».",
].join("\n");

/**
 * Блок вопросов в конце ответа — их интерфейс показывает кнопками.
 *
 * Отдельным правилом, а не частью разметки: в режиме «Коротко» вопросов нет,
 * и требовать их там — значит заставлять модель спорить с режимом.
 */
export const FOLLOW_UP_RULES = [
  "В самом конце ответа добавь блок с вопросами — их покажут кнопками:",
  "Что спросить дальше:",
  "- вопрос одним предложением",
  "- ещё один вопрос",
  "- третий вопрос",
  "Вопросы — короткие, по теме ответа, от лица человека, который спрашивает.",
].join("\n");

/**
 * Заголовок блока с вопросами: «Что спросить дальше:».
 *
 * Модель может оформить его как заголовок разметки («## Что спросить дальше»)
 * или выделить жирным («**Что спросить дальше:**») — все варианты узнаём.
 */
const FOLLOW_UP_HEADING =
  /^\s*(?:#{1,6}\s*)?(?:\*\*|__)?\s*что\s+спросить\s+дальше\s*:?\s*(?:\*\*|__)?\s*$/i;

/**
 * Заголовок блока вопросов, оформленный как «## Вопросы».
 *
 * Модель ставит такой заголовок перед «Что спросить дальше» или перед самим
 * списком вопросов. Без отдельной проверки он остался бы в тексте висящим
 * заголовком без содержимого: вопросы уезжают в кнопки, а заголовок — нет.
 */
const QUESTIONS_HEADING = /^\s*(?:#{1,6}\s*)?(?:\*\*|__)?\s*вопросы\s*:?\s*(?:\*\*|__)?\s*$/i;

/**
 * Метка источника, которую модель придумывает сама.
 *
 * В режимах с интернетом модель иногда помечает факты из каталога как
 * «[каталог]». Такой метки нет ни в одном блоке источников, и человек видит
 * её просто как лишние слова. Убирается вместе с выделением: иначе от
 * «**[каталог]**» осталось бы «****».
 *
 * Взгляд вперёд защищает настоящую ссылку: «[каталог](/fabrics/denim)» —
 * это ссылка на запись каталога, и трогать её нельзя.
 */
const INVENTED_MARKER = /[ \t]*(?:\*\*|__)?\[каталог[^\]\n]*\](?!\()(?:(?:\*\*|__))?/gi;

/** Знаки препинания, перед которыми модель часто оставляет лишний пробел. */
const SPACE_BEFORE_PUNCT = /[ \t]+([.,;:!?…»])/g;

/** Пробел после открывающей скобки или перед закрывающей. */
const SPACE_IN_BRACKETS = /([([])[ \t]+/g;
const SPACE_BEFORE_BRACKET = /[ \t]+([)\]])/g;

/** Два и больше пробела подряд: в обычном тексте это один пробел. */
const MULTI_SPACE = /[ \t]{2,}/g;

/**
 * Схлопывает пробелы внутри строки, не трогая отступ в её начале.
 *
 * Отступ значим для разметки: по нему вложенный список остаётся вложенным.
 */
function collapseInnerSpaces(line: string): string {
  const parts = /^([ \t]*)(.*)$/.exec(line);
  if (!parts) return line;
  return parts[1] + parts[2].replace(MULTI_SPACE, " ");
}

/** Три и больше пустых строк: между блоками хватает одной. */
const TOO_MANY_BREAKS = /\n{3,}/g;

/** Пункт списка с вопросом. */
const FOLLOW_UP_ITEM = /^\s*(?:[-*•]|\d+[.)])\s+(.*)$/;

/** Сколько вопросов из блока показываем в интерфейсе. */
export const MAX_FOLLOW_UPS = 3;

/** Какой длины может быть вопрос, чтобы поместиться в кнопку. */
const MAX_FOLLOW_UP_LENGTH = 120;

/**
 * Убирает огрехи форматирования, не трогая смысл текста.
 *
 * Правила намеренно простые: трогаются только пробелы, пустые строки и
 * висячие пробелы в конце строк. Разметка, ссылки и числа остаются как есть.
 *
 * Отступы в начале строки сохраняются: по ним разметка понимает вложенный
 * список, и схлопывание сломало бы вложенность.
 */
export function normalizeAnswer(text: string): string {
  return text
    .split("\n")
    .map((line) =>
      collapseInnerSpaces(line)
        .replace(SPACE_BEFORE_PUNCT, "$1")
        .replace(SPACE_IN_BRACKETS, "$1")
        .replace(SPACE_BEFORE_BRACKET, "$1")
        .replace(/[ \t]+$/, "")
    )
    .join("\n")
    .replace(TOO_MANY_BREAKS, "\n\n")
    .trim();
}

/** Снимает выделение с текста вопроса: «**вопрос**» → «вопрос». */
function stripEmphasis(text: string): string {
  return text
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/__(.+?)__/g, "$1")
    .replace(/\*(.+?)\*/g, "$1")
    .replace(/^[-–—]\s*/, "")
    .trim();
}

/** Ответ с вырезанным блоком вопросов. */
export type AnswerWithFollowUps = {
  /** Текст ответа без блока вопросов. */
  text: string;
  /** Вопросы для кнопок под ответом. */
  followUps: string[];
};

/**
 * Начало блока вопросов: индекс строки, с которой блок начинается.
 *
 * Блок встречается в двух видах: с заголовком «Что спросить дальше» и с
 * заголовком «Вопросы», который модель ставит перед первым. Второй узнаём
 * только если сразу за ним идёт список или первый заголовок: иначе «Вопросы»
 * может быть обычным разделом ответа, и его содержимое нельзя выбрасывать.
 *
 * Если встретились оба заголовка, блок начинается с более раннего: иначе
 * «Вопросы» остался бы в тексте висящим заголовком без содержимого.
 *
 * Возвращает -1, если блока нет.
 */
function findFollowUpStart(lines: string[]): number {
  const direct = lines.findIndex((line) => FOLLOW_UP_HEADING.test(line));
  const questions = findQuestionsHeading(lines);

  if (questions !== -1 && (direct === -1 || questions < direct)) return questions;
  return direct;
}

/**
 * Заголовок «Вопросы», за которым действительно идут вопросы.
 *
 * Проверяется содержимое после заголовка: за ним должен идти список или
 * первый заголовок блока. Иначе «Вопросы» — обычный раздел ответа, и его
 * нельзя выбрасывать вместе с вопросами.
 */
function findQuestionsHeading(lines: string[]): number {
  for (let i = 0; i < lines.length; i++) {
    if (!QUESTIONS_HEADING.test(lines[i])) continue;

    // Ищем первую содержательную строку после заголовка.
    for (let j = i + 1; j < lines.length; j++) {
      const next = lines[j];
      if (next.trim().length === 0) continue;
      if (FOLLOW_UP_HEADING.test(next) || FOLLOW_UP_ITEM.test(next)) return i;
      break;
    }
  }

  return -1;
}

/**
 * Достаёт из ответа блок «Что спросить дальше».
 *
 * Модель может оформить его по-разному: с заголовком и списком, без
 * заголовка, с нумерацией. Распознаём все эти варианты, а блок убираем из
 * текста: в интерфейсе вопросы показываются отдельными кнопками.
 *
 * Если блока нет, текст возвращается без изменений, а список вопросов пуст.
 */
export function extractFollowUps(text: string): AnswerWithFollowUps {
  const lines = text.split("\n");
  const blockStart = findFollowUpStart(lines);

  if (blockStart === -1) {
    return { text, followUps: [] };
  }

  const followUps: string[] = [];
  let tailStart = lines.length;

  for (let i = blockStart + 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim().length === 0) continue;
    // Второй заголовок внутри блока «Вопросы» — пропускаем, вопросы идут ниже.
    if (FOLLOW_UP_HEADING.test(line)) continue;

    const item = FOLLOW_UP_ITEM.exec(line);
    if (!item) {
      // Список закончился: дальше снова обычный текст.
      tailStart = i;
      break;
    }
    const question = stripEmphasis(item[1]).trim();
    if (!question || question.length > MAX_FOLLOW_UP_LENGTH) continue;
    if (followUps.includes(question)) continue;
    followUps.push(question);
    if (followUps.length >= MAX_FOLLOW_UPS) {
      tailStart = i + 1;
      break;
    }
  }

  // Текст после блока вопросов сохраняем: модель может дописать его в конце.
  // Отдельным абзацем — иначе он прилипает к предыдущей строке.
  const head = lines.slice(0, blockStart).join("\n").trim();
  const tail = lines.slice(tailStart).join("\n").trim();
  const rest = head && tail ? `${head}\n\n${tail}` : head || tail;
  return { text: rest, followUps };
}

/**
 * Убирает метку источника, которую модель придумала сама.
 *
 * Метки «[каталог]» нет ни в одном блоке источников: человек видит её
 * просто как лишние слова. Убирается до основной чистки, чтобы после
 * удаления не осталось пробела перед знаком препинания.
 */
function stripInventedMarkers(text: string): string {
  return text.replace(INVENTED_MARKER, "");
}

/**
 * Разбирает ответ на текст и вопросы для кнопок.
 *
 * Это то, что делается с ответом перед показом: огрехи форматирования
 * убираются, а блок вопросов выносится из текста отдельным списком.
 */
export function parseAnswer(text: string): AnswerWithFollowUps {
  return extractFollowUps(normalizeAnswer(stripInventedMarkers(text)));
}

/**
 * Сколько разных источников упомянуто в тексте ссылками [1], [2].
 *
 * По этому числу видно, однофамильны ли ссылки с источниками: если источники
 * есть, а ссылок в тексте нет, ответ получился без опоры на интернет.
 */
export function countCitations(text: string): number {
  const found = new Set<number>();
  for (const match of text.matchAll(/\[(\d{1,2})]/g)) {
    const index = Number(match[1]);
    if (index > 0) found.add(index);
  }
  return found.size;
}
