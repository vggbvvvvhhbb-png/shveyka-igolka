import { z } from "zod";

// ============================================================================
// ДИАЛОГИ
// ============================================================================

/**
 * Идентификатор диалога: строка из букв, цифр, дефиса и подчёркивания.
 * Такие идентификаторы используются и в URL, поэтому лишние символы
 * запрещены.
 */
export const ConversationIdSchema = z
  .string()
  .min(1, "Идентификатор диалога не может быть пустым")
  .max(100, "Идентификатор диалога слишком длинный")
  .regex(/^[a-zA-Z0-9_-]+$/, "Некорректный идентификатор диалога");

/** Роль сообщения: вопрос пользователя или ответ ассистента. */
export const ConversationRoleSchema = z.enum(["user", "assistant"]);

/** Тело запроса на создание диалога. */
export const CreateConversationSchema = z.object({
  title: z.string().trim().min(1, "Название не может быть пустым").max(120).optional(),
});

/** Тело запроса на добавление сообщения в диалог. */
export const AddMessageSchema = z.object({
  role: ConversationRoleSchema,
  content: z
    .string()
    .trim()
    .min(1, "Сообщение не может быть пустым")
    .max(4000, "Сообщение слишком длинное"),
});
